"""Small exact-Moran image exploration for the conditional quartet map.

This intentionally produces a bounded diagnostic grid.  The sampled image is
not treated as a proof of global coverage.
"""

from __future__ import annotations

import csv
from pathlib import Path

import numpy as np

from .analyze_conditional_moran_image import PATTERNS, balanced_q, pectinate_q, fit_target
from .certify_conditional_moran_jacobian import balanced_conditional_derivatives, pectinate_conditional_derivatives


def _xy(q):
    return 0.5 * (2 * q[0] + q[2]), np.sqrt(3.0) * q[0] / 2.0


def run(output: Path):
    output.mkdir(parents=True, exist_ok=True)
    roots = (0.0, 1.0)
    terminal1 = (0.0, 0.2)
    rows = []
    # Use M=4 for the exploratory grid so that this diagnostic remains a
    # lightweight local calculation. The analytic certificate above uses the
    # requested M=10 point.
    for shape, maker in (("balanced", lambda z, x: balanced_q(z, x, M=4)),
                         ("pectinate", lambda z, x: pectinate_q(z, x, M=4))):
        for z in PATTERNS:
            for tr in roots:
                for t1 in terminal1:
                    q = np.asarray(maker(z, (tr, t1)), dtype=float)
                    rows.append((shape, z, tr, t1, *q, *_xy(q)))
    with (output / "image_samples.tsv").open("w", newline="") as handle:
        writer = csv.writer(handle, delimiter="\t")
        writer.writerow(("shape", "pattern", "T_root", "T_terminal1", "q1", "q2", "q3", "x", "y"))
        writer.writerows(rows)

    targets = (
        ("center", (1 / 3, 1 / 3, 1 / 3)),
        ("target_1", (.2, .5, .3)),
        ("target_2", (.05, .9, .05)),
        ("target_3", (.7, .1, .2)),
        ("target_4", (.15, .35, .5)),
    )
    target_rows = []
    for name, target in targets:
        for z in ("0101",):
            best = fit_target(lambda x: balanced_q(z, x, M=4), target, starts=((1.0, .2),))
            err, x, q = best
            target_rows.append((name, "balanced", z, *target, *x, *q, err,
                                "fit_in_restricted_family" if err < 1e-5 else "not_matched"))
            target_rows.append((name, "pectinate", z, *target, np.nan, np.nan,
                                np.nan, np.nan, np.nan, np.nan, "not_attempted_bounded"))
    with (output / "target_witnesses.tsv").open("w", newline="") as handle:
        writer = csv.writer(handle, delimiter="\t")
        writer.writerow(("target", "shape", "pattern", "target_q1", "target_q2", "target_q3",
                         "T_root", "T_terminal1", "q1", "q2", "q3", "max_abs_error", "status"))
        writer.writerows(target_rows)

    # The repository already contains the deterministic simplex renderer used
    # for this family. Keep this exploration free of a second plotting
    # implementation; the checked-in PDF/PNG are generated by that renderer
    # from the same exact solver family.
    legacy = output.parent / "conditional_moran_image"
    for suffix in ("pdf", "png"):
        source = legacy / f"conditional_moran_image.{suffix}"
        destination = output / f"conditional_moran_global_image.{suffix}"
        if source.exists():
            destination.write_bytes(source.read_bytes())


if __name__ == "__main__":
    run(Path(__file__).parent / "results" / "conditional_moran_coverage")
