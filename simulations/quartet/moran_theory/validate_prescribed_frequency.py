"""Bounded validation for the prescribed-frequency quartet recursion.

The primary checks are deliberately independent of the implementation's
matrix exponential: a segmentwise Kolmogorov ODE integration is used as the
reference for time ordering, and the constant-frequency balanced recursion is
compared with the previously validated fixed-frequency implementation.

This script does not claim that a prescribed trajectory is an unconditional
Moran result.  A stochastic-history average is a separate calculation and is
only reported when histories generated by the simulator are supplied.
"""

